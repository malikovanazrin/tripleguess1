export function shuffle<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function pickCards(count: number): Card[] {
  return shuffle(FULL_DECK).slice(0, Math.min(count, FULL_DECK.length));
}
